// MW4 : armes triées par tier avec leurs classes, filtre par catégorie, lien source ; accueil : liens vers les jeux.
const url=f=>require('url').pathToFileURL(require('path').resolve(f)).href;
const {chromium}=require('playwright');
(async()=>{const b=await chromium.launch({});
const p=await b.newPage({viewport:{width:1100,height:900}});const e=[];p.on('pageerror',x=>e.push(x.message));
await p.goto(url('docs/mw4/index.html'));await p.waitForTimeout(300);
console.log('onglets',(await p.locator('.tabs [data-view]').allTextContents()).join(' | '));
console.log('armes',await p.locator('.wep').count(),'premier',await p.textContent('.wep h3'),await p.textContent('.wep .tier'));
console.log('classes M4',await p.locator('#m4-mw4 .build').count(),'|',(await p.locator('#m4-mw4 .build h4').allTextContents()).join(' / '));
console.log('1re ligne',(await p.locator('#m4-mw4 .build li').first().innerText()).replace(/\s+/g,' '));
console.log('source',await p.getAttribute('#m4-mw4 .src','href'));
await p.screenshot({path:'dist/mw4_armes.png'});
await p.click('[data-cat=SMG]');
console.log('filtre SMG',await p.locator('.wep').count());
await p.setViewportSize({width:390,height:844});await p.click('[data-cat=""]');await p.screenshot({path:'dist/mw4_mobile.png'});
await p.setViewportSize({width:1100,height:900});
await p.goto(url('docs/index.html'));await p.waitForTimeout(300);
console.log('accueil',await p.title(),'|',(await p.locator('.jeu').evaluateAll(l=>l.map(a=>a.getAttribute('href')))).join(' '));
await p.screenshot({path:'dist/accueil.png'});
console.log(e);await b.close();})();
